package com.medislot.service;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.medislot.dto.ClinicalDtos.MedicineView;
import com.medislot.dto.ClinicalDtos.PrescriptionDetail;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;

/** Renders a prescription as a PDF. Built-in fonts cover Latin text only. */
@Service
public class PrescriptionPdfService {

    public byte[] render(PrescriptionDetail d) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4, 40, 40, 50, 50);
        try {
            PdfWriter.getInstance(doc, out);
            doc.addTitle("Prescription");
            doc.addCreator("MediSlot");
            doc.open();

            Font h1 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, new Color(10, 84, 150));
            Font h2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 11);
            Font body = FontFactory.getFont(FontFactory.HELVETICA, 10);
            Font small = FontFactory.getFont(FontFactory.HELVETICA, 8, Color.GRAY);

            doc.add(new Paragraph(nz(d.hospitalName()), h1));
            doc.add(new Paragraph(nz(d.hospitalAddress()), body));
            doc.add(new Paragraph(" ", body));

            doc.add(new Paragraph("Dr. " + stripDr(nz(d.doctorName())), h2));
            doc.add(new Paragraph(nz(d.specialization())
                    + (d.qualification() == null ? "" : " | " + d.qualification()), body));
            doc.add(new Paragraph(" ", body));

            doc.add(new Paragraph("Patient: " + nz(d.patientName()), body));
            doc.add(new Paragraph("Date: " + d.date() + "    Appointment no.: " + d.appointmentId()
                    + "    Prescription no.: " + d.id(), body));
            doc.add(new Paragraph(" ", body));

            if (d.diagnosis() != null && !d.diagnosis().isBlank()) {
                doc.add(new Paragraph("Diagnosis", h2));
                doc.add(new Paragraph(d.diagnosis(), body));
                doc.add(new Paragraph(" ", body));
            }

            doc.add(new Paragraph("Medicines", h2));
            PdfPTable table = new PdfPTable(new float[]{3f, 2f, 2f, 2f, 3f});
            table.setWidthPercentage(100);
            table.setSpacingBefore(4f);
            for (String head : new String[]{"Medicine", "Dosage", "Frequency", "Duration", "Notes"}) {
                PdfPCell c = new PdfPCell(new Phrase(head, h2));
                c.setBackgroundColor(new Color(235, 241, 247));
                c.setPadding(5f);
                table.addCell(c);
            }
            if (d.medicines().isEmpty()) {
                PdfPCell c = new PdfPCell(new Phrase("No medicines prescribed.", body));
                c.setColspan(5);
                c.setPadding(6f);
                table.addCell(c);
            }
            for (MedicineView m : d.medicines()) {
                for (String v : new String[]{m.medicineName(), m.dosage(), m.frequency(), m.duration(), nz(m.instructions())}) {
                    PdfPCell c = new PdfPCell(new Phrase(v, body));
                    c.setPadding(5f);
                    table.addCell(c);
                }
            }
            doc.add(table);

            if (d.instructions() != null && !d.instructions().isBlank()) {
                doc.add(new Paragraph(" ", body));
                doc.add(new Paragraph("Instructions", h2));
                doc.add(new Paragraph(d.instructions(), body));
            }
            if (d.followUpDate() != null) {
                doc.add(new Paragraph(" ", body));
                doc.add(new Paragraph("Follow-up date: " + d.followUpDate(), h2));
            }

            Paragraph foot = new Paragraph("\nGenerated by MediSlot. This is a computer-generated document "
                    + "(demonstration data).", small);
            foot.setAlignment(Element.ALIGN_LEFT);
            doc.add(foot);
            doc.close();
        } catch (DocumentException e) {
            throw new IllegalStateException("Could not render the prescription PDF", e);
        }
        return out.toByteArray();
    }

    private static String nz(String s) {
        return s == null ? "" : s;
    }

    private static String stripDr(String name) {
        return name.regionMatches(true, 0, "Dr. ", 0, 4) ? name.substring(4) : name;
    }
}